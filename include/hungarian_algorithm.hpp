/**
 * @file include/hungarian_algorithm.hpp
 * @author Shvaikov
 *
 * Венгерский алгоритм решения задачи о назначениях за O(n^3).
 */

#ifndef INCLUDE_HUNGARIAN_ALGORITHM_HPP_
#define INCLUDE_HUNGARIAN_ALGORITHM_HPP_

#include <vector>
#include <limits>

namespace graph {

/**
 * @brief Венгерский алгоритм решения задачи о назначениях.
 *
 * @tparam T Тип элементов матрицы стоимостей. Должен быть знаковым
 * (целочисленным или с плавающей точкой), так как алгоритм использует
 * потенциалы, принимающие отрицательные значения.
 *
 * @param cost Прямоугольная матрица стоимостей размера n x m, где
 * cost[i][j] --- стоимость назначения работника i на работу j.
 * Требуется, чтобы число строк не превышало число столбцов (n <= m).
 * @param assignment Указатель на вектор, в который записывается результат.
 * После работы функции assignment->at(i) содержит номер столбца (работы),
 * назначенного строке (работнику) i. Нумерация с нуля.
 *
 * @return Функция возвращает минимальную суммарную стоимость назначения.
 *
 * Алгоритм находит назначение каждой из n строк на свой (различный) столбец
 * так, чтобы суммарная стоимость была минимальной. Реализация соответствует
 * классической версии за O(n^3) с потенциалами (см. http://e-maxx.ru/algo/
 * assignment_hungary). Внутри используется одномерная индексация с единицы,
 * чтобы упростить логику дополняющих путей.
 */
template<typename T>
T HungarianAlgorithm(const std::vector<std::vector<T>>& cost,
                     std::vector<size_t>* assignment) {
  /* Число строк (работников) и столбцов (работ). */
  size_t n = cost.size();
  size_t m = (n > 0) ? cost[0].size() : 0;

  /* Пустая матрица --- стоимость 0, назначений нет. */
  if (n == 0 || m == 0) {
    assignment->clear();
    return T();
  }

  /* "Бесконечность" для инициализации минимумов. К ней мы никогда не
   * прибавляем, поэтому переполнения не происходит. */
  const T inf = std::numeric_limits<T>::max();

  /* Потенциалы строк (u) и столбцов (v), массив паросочетания (p) и массив
   * для восстановления дополняющего пути (way). Везде нумерация с единицы,
   * поэтому размеры на единицу больше. p[j] --- строка, назначенная
   * столбцу j (0, если столбец свободен). */
  std::vector<T> u(n + 1, T());
  std::vector<T> v(m + 1, T());
  std::vector<size_t> p(m + 1, 0);
  std::vector<size_t> way(m + 1, 0);

  /* Последовательно добавляем в паросочетание каждую строку i. */
  for (size_t i = 1; i <= n; i++) {
    /* Столбец 0 --- фиктивный, служит началом дополняющего пути.
     * Записываем в него текущую добавляемую строку. */
    p[0] = i;
    size_t j0 = 0;

    /* minv[j] --- минимальная приведённая стоимость достижения столбца j.
     * used[j] --- помечен ли столбец j в текущем поиске пути. */
    std::vector<T> minv(m + 1, inf);
    std::vector<bool> used(m + 1, false);

    /* Поиск кратчайшего дополняющего пути в духе алгоритма Дейкстры. */
    do {
      used[j0] = true;
      size_t i0 = p[j0];
      T delta = inf;
      size_t j1 = 0;

      /* Перебираем все непомеченные столбцы, обновляя минимумы. */
      for (size_t j = 1; j <= m; j++) {
        if (!used[j]) {
          /* Приведённая стоимость ребра (i0, j). */
          T cur = cost[i0 - 1][j - 1] - u[i0] - v[j];

          if (cur < minv[j]) {
            minv[j] = cur;
            way[j] = j0;
          }

          if (minv[j] < delta) {
            delta = minv[j];
            j1 = j;
          }
        }
      }

      /* Пересчитываем потенциалы: вдоль найденного пути уменьшаем
       * приведённые стоимости на delta. */
      for (size_t j = 0; j <= m; j++) {
        if (used[j]) {
          u[p[j]] += delta;
          v[j] -= delta;
        } else {
          minv[j] -= delta;
        }
      }

      j0 = j1;
    } while (p[j0] != 0);  /* Пока не достигли свободного столбца. */

    /* Разворачиваем найденный дополняющий путь, обновляя паросочетание. */
    do {
      size_t j1 = way[j0];
      p[j0] = p[j1];
      j0 = j1;
    } while (j0 != 0);
  }

  /* Восстанавливаем назначение: для каждого занятого столбца j строка p[j]
   * назначена на этот столбец. Переходим к нумерации с нуля. */
  assignment->assign(n, 0);
  for (size_t j = 1; j <= m; j++) {
    if (p[j] != 0)
      (*assignment)[p[j] - 1] = j - 1;
  }

  /* Суммарную стоимость считаем напрямую по найденному назначению ---
   * это нагляднее, чем брать -v[0]. */
  T totalCost = T();
  for (size_t i = 0; i < n; i++)
    totalCost += cost[i][(*assignment)[i]];

  return totalCost;
}

}  // namespace graph

#endif  // INCLUDE_HUNGARIAN_ALGORITHM_HPP_
